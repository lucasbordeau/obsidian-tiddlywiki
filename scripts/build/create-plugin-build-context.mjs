import builtins from 'builtin-modules';
import esbuild from 'esbuild';
import { createDevVaultPlugin } from './create-dev-vault-plugin.mjs';

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

export function createPluginBuildContext({
  production = false,
  pluginFolder,
  outfile = 'main.js',
  absWorkingDir = process.cwd(),
} = {}) {
  const plugins = [];
  const hasDevelopmentVault = !production && Boolean(pluginFolder);

  if (hasDevelopmentVault) {
    plugins.push(createDevVaultPlugin(pluginFolder));
  }

  const buildOptions = {
    absWorkingDir,
    banner: {
      js: banner,
    },
    entryPoints: ['src/main.ts'],
    bundle: true,
    external: [
      'obsidian',
      'electron',
      '@codemirror/autocomplete',
      '@codemirror/collab',
      '@codemirror/commands',
      '@codemirror/language',
      '@codemirror/lint',
      '@codemirror/search',
      '@codemirror/state',
      '@codemirror/view',
      '@lezer/common',
      '@lezer/highlight',
      '@lezer/lr',
      ...builtins,
    ],
    format: 'cjs',
    target: 'es2018',
    logLevel: 'info',
    sourcemap: production ? false : 'inline',
    treeShaking: true,
    tsconfig: 'tsconfig.json',
    outfile,
    plugins,
  };

  return esbuild.context(buildOptions);
}
